    def test_absence_is_matched_by_identity_without_a_unit(self):
        """A known absence carries no unit and is compared on identity alone.

        A true absence has no unit and no experiment, so requiring one would manufacture
        a false negative. The absence that *does* earn a true negative is the production
        record that declares the same known absence (``not_reported``); a
        ``filtered_by_policy`` prediction is a pipeline outcome, not a confirmed
        scientific absence, so it is reported and excluded rather than rewarded.
        """
        absence = dict(kind="numeric", paper_uid="p01", question=3, item="CH4_flux",
                       variant="00_full", round=1, experiment_id=None, value=None,
                       unit=None, status="not_reported")
        agreed = evaluate_records([dict(absence)], [absence], "adjudicated")
        self.assertEqual(agreed["metrics"]["true_negative"], 1)
        self.assertEqual(agreed["metrics"]["false_negative"], 0)
        self.assertIsNone(agreed["metrics"]["exact_match_recall"])

        prediction = dict(absence, status="filtered_by_policy")
        result = evaluate_records([prediction], [absence], "adjudicated")
        self.assertEqual(result["metrics"]["true_negative"], 0)
        self.assertEqual(result["metrics"]["false_negative"], 0)
        self.assertEqual(result["metrics"]["false_positive"], 0)
        # Excluded from the truth denominators: the known-absence denominator counts the
        # reference, but the diagnostic prediction never becomes a scored verdict.
        self.assertEqual(result["counts"]["not_reported_true_absence"], 1)
        self.assertEqual(result["counts"]["comparable_gold"], 0)
        self.assertEqual(result["counts"]["unmatched_gold"], 1)
        self.assertIn("reference_not_reported_prediction_diagnostic",
                      [c["reason"] for c in result["unaligned"]])
        self.assertEqual(result["diagnostics"]["filtered_by_policy"], 1)

